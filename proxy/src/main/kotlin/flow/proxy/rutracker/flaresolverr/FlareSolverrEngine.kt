package flow.proxy.rutracker.flaresolverr

import io.ktor.client.engine.HttpClientEngineBase
import io.ktor.client.engine.HttpClientEngineConfig
import io.ktor.client.request.HttpRequestData
import io.ktor.client.request.HttpResponseData
import io.ktor.http.HttpMethod
import io.ktor.http.HttpProtocolVersion
import io.ktor.http.HttpStatusCode
import io.ktor.http.content.OutgoingContent
import io.ktor.http.headersOf
import io.ktor.util.date.GMTDate
import io.ktor.utils.io.ByteReadChannel
import kotlin.coroutines.coroutineContext
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job

/**
 * A Ktor [HttpClientEngine] that never talks to rutracker.org directly - every request is relayed
 * through [FlareSolverrClient] (a real, remotely-driven Chromium browser) instead.
 *
 * Rutracker.org now sits behind a Cloudflare managed challenge on every endpoint except the
 * static index page. That challenge ties its `cf_clearance` cookie to the TLS/JA3 fingerprint of
 * the connection that solved it - a fingerprint generated by the network stack itself, below the
 * HTTP layer, that no header or cookie on a plain client (OkHttp, Ktor CIO, curl, ...) can
 * reproduce. Routing every request through an actual browser sidesteps the problem entirely
 * instead of trying to impersonate one.
 *
 * [RuTrackerInnerApiImpl] (shared with the Android app, in `core:network:rutracker`) builds
 * ordinary Ktor requests against `login.php`, `tracker.php`, etc. with no awareness of any of
 * this - this engine is swapped in underneath it in [flow.proxy.rutracker.api.HttpClientFactory],
 * so no route or HTML-parsing code needs to change.
 */
internal class FlareSolverrEngine(
    private val flareSolverr: FlareSolverrClient,
) : HttpClientEngineBase("flaresolverr") {

    override val dispatcher = Dispatchers.IO
    override val config = HttpClientEngineConfig()

    override suspend fun execute(data: HttpRequestData): HttpResponseData {
        val cookies = extractCookies(data.headers["Cookie"])
        val url = data.url.toString()
        val solution = if (data.method == HttpMethod.Post) {
            flareSolverr.post(url, extractFormBody(data.body), cookies)
        } else {
            flareSolverr.get(url, cookies)
        }
        return toResponseData(solution)
    }

    /**
     * FlareSolverr's `response` field is already a decoded Unicode string - the real browser it
     * drives parsed rutracker's Windows-1251 bytes into its DOM long before we ever see this, so
     * unlike the direct-connection path there is no charset to juggle here: round-trip it as
     * plain UTF-8 and declare that explicitly, since we don't set any other response headers for
     * callers to infer a charset from.
     */
    private suspend fun toResponseData(solution: FlareSolverrSolution): HttpResponseData {
        val callContext = coroutineContext + Job(coroutineContext[Job])
        return HttpResponseData(
            statusCode = HttpStatusCode.fromValue(solution.status),
            requestTime = GMTDate(),
            headers = headersOf("Content-Type", listOf("text/html; charset=UTF-8")),
            version = HttpProtocolVersion.HTTP_1_1,
            body = ByteReadChannel(solution.response.toByteArray(Charsets.UTF_8)),
            callContext = callContext,
        )
    }

    /**
     * [RuTrackerInnerApiImpl]'s POST bodies are already percent-encoded into plain ASCII bytes
     * (using Windows-1251 for any Cyrillic form values, so rutracker sees the exact same bytes it
     * would from a direct connection) before they ever reach this engine - decoding those ASCII
     * bytes as ISO-8859-1 here just recovers the same percent-encoded string, unchanged, to hand
     * to FlareSolverr as `postData`.
     */
    private fun extractFormBody(content: OutgoingContent): String {
        val bytes = (content as? OutgoingContent.ByteArrayContent)?.bytes() ?: ByteArray(0)
        return bytes.toString(Charsets.ISO_8859_1)
    }

    /**
     * Only the first `name=value` pair from the caller's `Cookie` header is rutracker's real
     * session cookie - [RuTrackerInnerApiImpl] builds that header from the raw `Set-Cookie` value
     * it captured at login, which can carry trailing `; path=...` /`; HttpOnly` attributes that
     * aren't valid `Cookie` header content but that rutracker's own server tolerates. FlareSolverr
     * is stricter, so only the leading pair is forwarded.
     */
    private fun extractCookies(rawCookieHeader: String?): List<FlareSolverrCookieInput> {
        val entry = rawCookieHeader?.split(";")?.firstOrNull()?.trim() ?: return emptyList()
        val parts = entry.split("=", limit = 2)
        if (parts.size != 2) return emptyList()
        return listOf(FlareSolverrCookieInput(name = parts[0].trim(), value = parts[1].trim(), domain = "rutracker.org"))
    }
}
